
import hashlib
import os 
import hmac
import random
import threading
import time
from typing import Tuple
from Crypto.Cipher import AES
from Crypto.Util.Padding import pad
from ecdsa import NIST256p, SigningKey, VerifyingKey


class SecureVault:
    """
    Class representing secure cryptographic key storage and management system.

    Attributes:
        id (int): A unique identifier for the vault, generated randomly during initialization.
        keys (list[bytes]): A list of cryptographic keys, each of size `key_size` bytes.

    Raises:
        ValueError: If an empty list of indices is provided to `perform_xor_over_keys` or if
            the input data for `update_keys` is empty.
        IndexError: If `update_keys` is called when the vault contains no keys.
    """
    
    def __init__(self, number_of_keys:int = 10, key_size:int = 16) -> None:
        """
        Args:
            number_of_keys (int): Number of keys to generate
            key_size (int): Size of each key in bytes
        """
        self.id = random.randint(1, 1000)
        self.keys = [os.urandom(key_size) for _ in range(number_of_keys)]


    def perform_xor_over_keys(self, index_list: list[int]) -> bytes:
        """
        Args:
            index_list (list[int]): List of key indexes
        """
        if not index_list or len(index_list) == 0:
            raise ValueError("index_list is empty.")
        
        key = self.keys[index_list[0]]

        for idx in index_list[1:]:
            key = bytes(x ^ y for x, y in zip(key, self.keys[idx]))

        return key


    def update_keys(self, data: bytes) -> None:
        """        
        Args:
            data (bytes): Input data for key update derivation
        """

        if not self.keys:
            raise IndexError("There are no keys in the vault.")
        
        if not data:
            raise ValueError("The input 'data' cannot be empty.")

        message = b''.join(self.keys)
        h = hmac.new(data, message, hashlib.sha256).digest()
        
        key_len = len(self.keys[0])
        key_number = len(self.keys)
        partitions = [h[i : i + key_len] for i in range(0, len(h), key_len)]
        for i in range(key_number):
            self.keys[i] = bytes(x ^ y for x, y in zip(self.keys[i], partitions[i % len(partitions)]))



class Server(threading.Thread):
    """
    Class representing the server responsible for device authentication and vault synchronization.
    Implements a multi-step authentication protocol using ECC signatures and vault-based challenges.

    Attributes:
        id (int): Unique identifier for the server.
        c1_length (int): Number of random vault key indices to sample for Challenge 1.
        key_size (int): Size (in bytes) of the encryption keys used in AES.
        lock (threading.Lock): Lock for synchronizing access to shared resources (e.g., `registered_devices_vault`).
        registered_devices_ECC (dict): Tracks devices registered for ECC-based authentication.
        registered_devices_vault (dict): Tracks devices registered for vault-based authentication.
            Each entry maps `device_id` to a dictionary containing:
                - vault_id (int): ID of the associated vault.
                - c1 (list): Random vault key indices for Challenge 1.
                - r1 (bytes): Random nonce for Challenge 1.
                - c2 (list): Vault key indices received from the device.
                - r2 (bytes): Random nonce received from the device.
                - t1 (bytes): Temporary key material received from the device.
                - t2 (bytes): Temporary key material generated by the server.
        vault (SecureVault): Shared vault for key storage and synchronization.
    """

    def __init__(self, vault:SecureVault, id:int=0, c1_length:int=0, key_size:int=0):
        super().__init__()
        self.id = id
        self.c1_length = c1_length
        self.key_size = key_size
        self.lock = threading.Lock()
        self.registered_devices_ECC = {}
        self.registered_devices_vault = {}
        self.vault = vault


    def register_device_secure_vault(self, device_id: int) -> None:
        print(f"Server {self.id} registering device {device_id}.")
        self.lock.acquire()
        try:
            self.registered_devices_vault[device_id] = {"vault_id": self.vault.id}
        except Exception as ex:
            print(f"Error in registration of device {device_id}")
            print(ex)
            self.lock.release()

    
    def register_device_ECC(self, device_id:int, public_key_pem=None) -> None:
        print(f"Server {self.id} registering device {device_id}.")
        if public_key_pem: 
            public_key = VerifyingKey.from_pem(public_key_pem)
            self.registered_devices_ECC[device_id] = {"public_key": public_key}
        

    def generate_challenge_1(self, device_id:int) -> Tuple[list, bytes]:
        print(f"Server {self.id} is generating Challenge 1 for device {device_id}.")

        registrered = device_id in self.registered_devices_vault
        if not registrered:
            raise Exception("Invalid session for device.")
        
        c1 = random.sample(range(len(self.vault.keys)), self.c1_length)
        r1 = os.urandom(self.key_size)  
        self.registered_devices_vault[device_id]["c1"] = c1
        self.registered_devices_vault[device_id]["r1"] = r1
        return (c1, r1)


    def validate_challenge_1(self, device_id:int, encrypted_response:bytes) -> bool:
        print(f"Server {self.id} validating Challenge 1 response for device {device_id}.")
        registrered = device_id in self.registered_devices_vault
        if not registrered:
            print(f"Invalid session for device {device_id}.")
            self.lock.release()
            return False
        
        c1 = self.registered_devices_vault[device_id]["c1"]
        r1 = self.registered_devices_vault[device_id]["r1"]

        k1 = self.vault.perform_xor_over_keys(c1)
        decrypted_response = AES.new(k1, AES.MODE_ECB).decrypt(encrypted_response)
        
        r1_received = decrypted_response[:16]
        t1 = decrypted_response[16:32]
        c2 = list(decrypted_response[32:35])
        r2 = decrypted_response[35:51]

        if r1_received != r1:
            print(f"Validation for device {device_id} failed.")
            self.lock.release()
            return False

        self.registered_devices_vault[device_id]["c2"] = c2
        self.registered_devices_vault[device_id]["r2"] = r2
        self.registered_devices_vault[device_id]["t1"] = t1
        return True


    def generate_final_response(self, device_id) -> bytes:
        print(f"Server {self.id} generating final response for device {device_id}.")
        registrered = device_id in self.registered_devices_vault
        if not registrered:
            print(f"Invalid session for device {device_id}.")
            self.lock.release()
            return False
        
        c2 = self.registered_devices_vault[device_id]["c2"]
        r2 = self.registered_devices_vault[device_id]["r2"]
        t1 = self.registered_devices_vault[device_id]["t1"]

        key2 = self.vault.perform_xor_over_keys(c2)
        dynamic_key = bytes(x ^ y for x, y in zip(key2, t1))
        
        t2 = os.urandom(16)
        payload = r2 + t2
        encrypted = AES.new(dynamic_key, AES.MODE_ECB).encrypt(pad(payload, 16))
        
        self.registered_devices_vault[device_id]["t2"] = t2
        return encrypted


    def synchronize_vault(self, device_id) -> None:
        print(f"Server {self.id} synchronizing vault for device {device_id}.")
        registrered = device_id in self.registered_devices_vault
        if not registrered:
            print(f"Invalid session for device {device_id}.")
            self.lock.release()
            return
        
        # Update vault with session nonces
        r1 = self.registered_devices_vault[device_id]["r1"]
        r2 = self.registered_devices_vault[device_id]["r2"]
        self.vault.update_keys(r1 + r2)
        self.lock.release()


    def is_signature_valid_ECC(self, device_id:int, key, signature) -> bool:
        if device_id not in self.registered_devices_ECC:
            print(f"Device {device_id} not registered for ECC authentication.")
            return False
        
        public_key = self.registered_devices_ECC[device_id]["public_key"]
        
        try:
            result = public_key.verify(signature, key)
        except Exception:
            print(f"Device {device_id} provided an invalid signature.")
            result = False
            
        return result



class DeviceSVAuth(threading.Thread):
    """
    Class representing a device that interacts with the server for authentication and vault synchronization.
    Implements a multi-step authentication protocol using vault-based challenges and AES encryption.
    Attributes:
        device_id (int): Unique identifier for the device.
        server (Server): Reference to the server handling authentication.
        key_size (int): Size (in bytes) of the encryption keys used in AES.
        vault (SecureVault): Shared vault for key storage and synchronization.
        c2_length (int): Length of the random sample of vault keys used in Challenge 2.
        authentication (dict): Tracks authentication status and performance metrics:
            - authenticated (bool): True if authentication succeeded.
            - encrypt_time (float): Time taken for Challenge 1 encryption (seconds).
            - decrypt_time (float): Time taken for final response decryption (seconds).
            - vault_update_time (float): Time taken for vault synchronization (seconds).
    Raises:
        Exception: If any step of the authentication protocol fails (e.g., challenge generation,
            validation, or final response decryption).
    """
    
    def __init__(self, device_id:int, server:Server, c2_length:int, key_size:int, vault: SecureVault):
        super().__init__()
        self.device_id = device_id
        self.server = server
        self.key_size = key_size
        self.vault = vault
        self.c2_length = c2_length
        self.authentication = {
            "authenticated": False,
            "encrypt_time": None,
            "decrypt_time": None,
            "vault_update_time": None
        }

    def run(self):
        self.server.register_device_secure_vault(self.device_id)

        print(f"Device {self.device_id} starting Challenge 1.")
        c1, r1 = self.server.generate_challenge_1(self.device_id)
        if not c1:
            raise Exception("Failed to get Challenge 1 from server.")

        print(f"Device {self.device_id} generating Challenge 2.")
        encrypt_start = time.time()
        key1 = self.vault.perform_xor_over_keys(c1)
        t1 = os.urandom(self.key_size)
        c2 = random.sample(range(len(self.vault.keys)), self.c2_length)
        r2 = os.urandom(self.key_size)
        payload = r1 + t1 + bytes(c2) + r2
        encrypted_response = AES.new(key1, AES.MODE_ECB).encrypt(pad(payload, self.key_size))
        self.authentication["encrypt_time"] = time.time() - encrypt_start

        decrypt_start = time.time()
        if not self.server.validate_challenge_1(self.device_id, encrypted_response):
            raise Exception("Challenge 1 response validation failed.")

        print(f"Device {self.device_id} waiting for final response.")
        final_response = self.server.generate_final_response(self.device_id)
        if not final_response:
            raise Exception("Failed to get final response from server.")

        print(f"Device {self.device_id} decrypting final response.")
        key2 = self.vault.perform_xor_over_keys(c2)
        dynamic_key = bytes(x ^ y for x, y in zip(key2, t1))
        
        decrypted = AES.new(dynamic_key, AES.MODE_ECB).decrypt(final_response)
        self.authentication["decrypt_time"] = time.time() - decrypt_start
        
        print(f"Device {self.device_id} validating server {self.server.id} response.")
        r2_received = decrypted[:16]
        if r2_received == r2:
            print(f"Device {self.device_id} authenticated successfully. Updating vault.")
            vault_start = time.time()
            self.server.synchronize_vault(self.device_id)
            self.authentication["vault_update_time"] = time.time() - vault_start
            self.authentication["authenticated"] = True



class DeviceECCAuth(threading.Thread):
    """
    Class representing a device that uses ECC for authentication with the server.
    Implements key generation, signing, and verification using ECC signatures.

    Attributes:
        device_id: Unique identifier for the device.
        server: Reference to the server handling the authentication.
        private_key (SigningKey): ECC private key used for signing.
        public_key (VerifyingKey): ECC public key derived from the private key, used for verification.
        status (str): Authentication status ("Success" or "Failed").
        key_gen_time (float): Time taken to generate the random key (in seconds).
        sign_time (float): Time taken to sign the key (in seconds).
        verify_time (float): Time taken by the server to verify the signature (in seconds).
    """

    def __init__(self, device_id:int, server:Server):
        super().__init__()
        self.device_id = device_id
        self.server = server
        self.private_key = SigningKey.generate(curve=NIST256p)
        self.public_key = self.private_key.verifying_key
        self.authentication = {
            "authenticated": False,
            "key_gen_time": 0,
            "sign_time": 0,
            "verify_time": 0
        }

    def get_public_key(self) -> bytes:
        return self.public_key.to_pem()

    def sign_key(self, key) -> bytes:
        start_time = time.time()
        sign = self.private_key.sign(key)
        self.authentication["sign_time"] = time.time() - start_time
        return sign
    
    def run(self) -> None:
        self.server.register_device_ECC(self.device_id, self.get_public_key())

        start_time = time.time()
        key = os.urandom(32)
        key_gen_time = time.time() - start_time
        self.authentication["key_gen_time"] = key_gen_time
        print(f"Device {self.device_id} generated key in {key_gen_time*1000:.4f} ms.")

        signature = self.sign_key(key)
        print(f"Device {self.device_id} signed key in {self.authentication["sign_time"]*1000:.4f} ms.")

        start_time = time.time()
        verification_result = self.server.is_signature_valid_ECC(self.device_id, key, signature)
        self.authentication["authenticated"] = verification_result
        self.authentication["verify_time"] = time.time() - start_time

        




